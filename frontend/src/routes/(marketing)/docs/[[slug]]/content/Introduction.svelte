<h1>Introduction</h1>

<p>
    Hi there blogger 👋,
</p>

<p>
    Running a blog has never been easier. Installing plugins, keeping up with updates, and managing services are not for general bloggers. We believe that blogging should be easy for everyone. That's why we created <a href="/">Hyvor Blogs</a>. All the technical stuff is handled by us. You just need to focus on writing.
</p>

<h2 id="get-started">
    How to get started?
</h2>

<p>Visit the <a href="https://blogs.hyvor.com/console">Hyvor Blogs Console</a> to create a new blog. The Console is where you will be managing all of your blogs. You can access the Console using your HYVOR account. Each account can have multiple blogs.</p>

<h2 id="features">
    Features
</h2>

<p>
    Hyvor Blogs is an all-in-one blogging platform. Here are some of its main features with links to learn more about them.
</p>

<ul>
    <li>
        <strong><a href="/docs/writing">Powerful writing tools</a> </strong> - You can write your posts in the built-in rich text editor. Adding images, rich media, and code snippets are easy-peasy.
    </li>
    <li>
        <strong><a href="/docs/languages">Multi-language support</a></strong> - Want to reach a wider audience? Enable multiple languages for your blog and start translating. We support AI translations via DeepL as well.
    </li>
    <li>
        <strong><a href="/docs/theme">Customizable Themes</a></strong> - You can choose a theme from our theme library or create your own theme from scratch.
    </li>
	<li>
        <strong><a href="/docs/users">Invite your team members</a></strong> - Write posts with your team members. Multiple roles are available.
    </li>
    <li>
        <strong><a href="/docs/custom-domain">Custom Domain</a></strong> - Host your blog on your own domain like example.com or blog.example.com.
    </li>
    <li>
        <strong><a href="/docs/subdirecotory">Sub-directory Hosting</a></strong> - Host your blog on your a sub-directory like example.com/blog. Multiple integrations are available.
    </li>
    <li>
        <strong><a href="/docs/seo">In-built SEO</a></strong> - Hyvor Blogs is built with SEO in mind. Most of the technical SEO stuff is handled by us. You just need to focus on writing.
    </li>
    <li>
        <strong><a href="/docs/custom-code">Integrations via Custom Code</a></strong> - Want to add analytics, ads, or other integrations? Just add the code snippet to the Custom Code section.
    </li>
</ul>

