<h1>Tags</h1>

<p>
    Tags are used to "group" similar posts. You can assign one or more tags to a post.
</p>


Each tag creates a tag index page (`/tag/tag-slug`), which lists the posts of that tag. This makes easy for users to browse posts of a specific slug. For example, our [official blog](/blog) has multiple tags, and you can visit [/blog/tag/seo](/blog/tag/seo) to see SEO-related posts.

