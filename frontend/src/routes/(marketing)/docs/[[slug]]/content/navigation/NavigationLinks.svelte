<h1 id="navigation">Navigation Links</h1>

<p>
    Navigation links are shown in the header and footer of your blog. You can configure them in the <strong>Settings &rarr; Navigation Links</strong> section of the Console.
</p>

<h2 id="create">
    Create a Navigation Link
</h2>

<p>To create a navigation link, </p>
<ol>
    <li>Go to <strong>Settings &rarr; Navigation Links</strong></li>
    <li>Click the <strong>Create Navigation</strong> button</li>
    <li>Fill in the details: Name, URL, Type</li>
    <li>Click the <strong>Add</strong> button</li>
</ol>

