<h1>Media</h1>

<p>
    "Media" refers to the files you upload in your blog. It can be images, videos, audio, or any other file. Visit <strong>Tools &rarr; Media Library</strong> to manage your blog media.
</p>

<h2 id="images">
    Images
</h2>

<p>
    "A picture is worth a thousand words". Adding pictures to your blog posts is a great way to make them more interesting and informative. But be careful – using too many or large images can slow down your website. Hyvor Blogs automatically optimizes images for you when possible.
</p>

<p>
    You can upload images in post editor, in the media library, or in blog settings such as logo, favicon, etc. The following image formats are supported:
</p>

<ul>
    <li>PNG - <code>.png</code></li>
    <li>JPEG - <code>.jpg</code>, <code>.jpeg</code>, <code>.jfif</code>, <code>.pjpeg</code>, <code>.pjp</code></li>
    <li>GIF - <code>.gif</code></li>
    <li>APNG - <code>.apng</code></li>
    <li>AVIF - <code>.avif</code></li>
    <li>SVG - <code>.svg</code></li>
    <li>WebP - <code>.webp</code></li>
</ul>

<h3 id="webp">
    WebP Conversion
</h3>

<p>
    <a href="https://en.wikipedia.org/wiki/WebP" rel="nofollow" target="_blank">WebP</a> images are 25-34% smaller than JPEG/PNG images of the same quality. It is recommended nowadays to use WebP in websites whenever possible as all modern browsers support WebP images.
</p>