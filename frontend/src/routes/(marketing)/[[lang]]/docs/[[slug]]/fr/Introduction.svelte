<h1>Introduction</h1>

<p>Bonjour cher blogueur 👋,</p>

<p>
	Gérer un blog n'a jamais été aussi facile. Installer des plugins, suivre les mises à jour et gérer
	des services ne sont pas faits pour les blogueurs ordinaires. Nous pensons que bloguer devrait être
	facile pour tout le monde. C'est pourquoi nous avons créé <a href="/">Hyvor Blogs</a>. Tous les aspects
	techniques sont pris en charge par nous. Vous n'avez qu'à vous concentrer sur l'écriture.
</p>

<h2 id="get-started">Comment commencer ?</h2>

<p>
	Visitez la <a href="https://blogs.hyvor.com/console">Console Hyvor Blogs</a> pour créer un nouveau blog. La
	Console est l'endroit où vous gérerez tous vos blogs. Vous pouvez accéder à la Console en utilisant votre compte
	HYVOR. Chaque compte peut avoir plusieurs blogs.
</p>

<h2 id="features">Fonctionnalités</h2>

<p>
	Hyvor Blogs est une plateforme de blogging tout-en-un. Voici quelques-unes de ses principales fonctionnalités
	avec des liens pour en savoir plus à leur sujet.
</p>

<ul>
	<li>
		<strong><a href="/docs/writing">Outils d'écriture puissants</a> </strong> - Vous pouvez rédiger vos articles
		dans l'éditeur de texte enrichi intégré. Ajouter des images, du contenu multimédia riche et des extraits de
		code est un jeu d'enfant.
	</li>
	<li>
		<strong><a href="/docs/languages">Support multilingue</a></strong> - Vous voulez toucher un public plus large ?
		Activez plusieurs langues pour votre blog et commencez à traduire. Nous prenons également en charge les traductions
		par IA via DeepL.
	</li>
	<li>
		<strong><a href="/docs/theme">Thèmes personnalisables</a></strong> - Vous pouvez choisir un thème dans notre
		bibliothèque de thèmes ou créer votre propre thème à partir de zéro.
	</li>
	<li>
		<strong><a href="/docs/users">Invitez les membres de votre équipe</a></strong> - Rédigez des articles avec les
		membres de votre équipe. Plusieurs rôles sont disponibles.
	</li>
	<li>
		<strong><a href="/docs/custom-domain">Domaine personnalisé</a></strong> - Hébergez votre blog sur votre propre
		domaine comme example.com ou blog.example.com.
	</li>
	<li>
		<strong><a href="/docs/subdirectory">Hébergement en sous-répertoire</a></strong> - Hébergez votre blog dans un
		sous-répertoire comme example.com/blog. Plusieurs intégrations sont disponibles.
	</li>
	<li>
		<strong><a href="/docs/seo">SEO intégré</a></strong> - Hyvor Blogs est conçu en pensant au SEO. La plupart des
		aspects techniques du SEO sont pris en charge par nous. Vous n'avez qu'à vous concentrer sur l'écriture.
	</li>
	<li>
		<strong><a href="/docs/custom-code">Intégrations via code personnalisé</a></strong> - Vous voulez ajouter des
		analyses, des publicités ou d'autres intégrations ? Ajoutez simplement l'extrait de code dans la section Code
		personnalisé.
	</li>
</ul>

